import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.resolve(__dirname, "..");

const sourcePath = path.join(
  root,
  "docs-source",
  "ocr-interfaces",
  "latest",
  "interface-classification.json",
);
const catalogPath = path.join(root, "src", "data", "ocrDocs.ts");
const outputPath = path.join(root, "src", "data", "generated", "interfaceClassification.generated.ts");

const recordIdPattern = /^[A-Z]{3}-\d{3}$/;

function extractCatalogSlugs(content) {
  const match = content.match(
    /const interfaceCatalogSeed:\s*InterfaceCardSeed\[\]\s*=\s*\[([\s\S]*?)\];\s*\n\s*export const interfaceCatalog:/,
  );
  if (!match) {
    throw new Error("Could not locate interfaceCatalogSeed in src/data/ocrDocs.ts");
  }
  return [...match[1].matchAll(/slug:\s*"([^"]+)"/g)].map((item) => item[1]);
}

function assertNoDuplicates(values, label) {
  const seen = new Set();
  const dup = new Set();
  for (const value of values) {
    if (seen.has(value)) {
      dup.add(value);
    }
    seen.add(value);
  }
  if (dup.size > 0) {
    throw new Error(`${label} contains duplicates: ${[...dup].join(", ")}`);
  }
}

function renderGeneratedFile(payload) {
  return `/* eslint-disable */
// AUTO-GENERATED by scripts/build-interface-classification.mjs
// Source: docs-source/ocr-interfaces/latest/interface-classification.json

export type BusinessCategoryCode = ${payload.taxonomy.map((t) => `"${t.code}"`).join(" | ")};
export type BusinessCategoryLabel = ${payload.taxonomy.map((t) => `"${t.label}"`).join(" | ")};

export interface InterfaceClassificationRecord {
  slug: string;
  categoryCode: BusinessCategoryCode;
  categoryLabel: BusinessCategoryLabel;
  recordId: string;
}

export const interfaceClassificationVersion = "${payload.version}";

export const businessTaxonomy = ${JSON.stringify(payload.taxonomy, null, 2)} as const;

export const interfaceClassificationRecords = ${JSON.stringify(payload.records, null, 2)} as const;

export const categories = businessTaxonomy.map((item) => item.label);

export const recordIdBySlug = Object.fromEntries(
  interfaceClassificationRecords.map((item) => [item.slug, item.recordId]),
) as Record<string, string>;

export const categoryBySlug = Object.fromEntries(
  interfaceClassificationRecords.map((item) => [item.slug, item.categoryLabel]),
) as Record<string, BusinessCategoryLabel>;
`;
}

async function main() {
  const [sourceRaw, catalogRaw] = await Promise.all([
    fs.readFile(sourcePath, "utf8"),
    fs.readFile(catalogPath, "utf8"),
  ]);

  const source = JSON.parse(sourceRaw);
  const taxonomyCodes = source.taxonomy.map((item) => item.code);
  const recordSlugs = source.records.map((item) => item.slug);
  const recordIds = source.records.map((item) => item.recordId);
  const catalogSlugs = extractCatalogSlugs(catalogRaw);

  assertNoDuplicates(taxonomyCodes, "taxonomy.code");
  assertNoDuplicates(recordSlugs, "records.slug");
  assertNoDuplicates(recordIds, "records.recordId");

  for (const code of source.records.map((item) => item.categoryCode)) {
    if (!taxonomyCodes.includes(code)) {
      throw new Error(`Unknown categoryCode in records: ${code}`);
    }
  }

  for (const recordId of recordIds) {
    if (!recordIdPattern.test(recordId)) {
      throw new Error(`Invalid recordId format: ${recordId}`);
    }
  }

  const sourceSlugSet = new Set(recordSlugs);
  const catalogSlugSet = new Set(catalogSlugs);

  const missingInSource = catalogSlugs.filter((slug) => !sourceSlugSet.has(slug));
  const extraInSource = recordSlugs.filter((slug) => !catalogSlugSet.has(slug));
  if (missingInSource.length > 0 || extraInSource.length > 0) {
    throw new Error(
      `Slug coverage mismatch.\nMissing in source: ${missingInSource.join(", ") || "(none)"}\nExtra in source: ${
        extraInSource.join(", ") || "(none)"
      }`,
    );
  }

  if (recordSlugs.length !== 44) {
    throw new Error(`Expected 44 records, got ${recordSlugs.length}`);
  }

  const codeToLabel = Object.fromEntries(source.taxonomy.map((item) => [item.code, item.label]));
  const generatedPayload = {
    version: source.version,
    taxonomy: source.taxonomy,
    records: source.records.map((record) => ({
      slug: record.slug,
      categoryCode: record.categoryCode,
      categoryLabel: codeToLabel[record.categoryCode],
      recordId: record.recordId,
    })),
  };

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, renderGeneratedFile(generatedPayload), "utf8");

  console.log(`Classification version: ${source.version}`);
  console.log(`Taxonomy categories: ${source.taxonomy.length}`);
  console.log(`Records validated: ${recordSlugs.length}`);
  console.log(`Generated: ${path.relative(root, outputPath)}`);
}

main().catch((error) => {
  console.error(error.message || error);
  process.exitCode = 1;
});
